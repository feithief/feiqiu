function plot_second_target_result(secondResult, whiteXY, config)
%PLOT_SECOND_TARGET_RESULT 画出第 2 个目标点的几何关系和验算过程。
%
% 图 1：xy 色域图，标出白点 W、目标点 T、交点 P、验证点 V，
%       并在线段上标出 lambda 与 1-lambda。
% 图 2：把亮度分解、PWM 分解、以及 RGB_to_xyY_32000 的回算过程画出来。

    if nargin < 2
        whiteXY = [0.3090 0.3176];
    end
    if nargin < 3 || isempty(config)
        config = default_white_mix_config();
    end

    [xyY_red, xyY_green, xyY_blue] = fixed_rgb_primaries(config.verifyPrimaries);
    triangleXY = normalize_intersection_triangle(config.intersectionPrimaries);

    targetXY = [get_value(secondResult, '目标x'), get_value(secondResult, '目标y')];
    intersectXY = [get_value(secondResult, '交点x'), get_value(secondResult, '交点y')];
    verifyXY = [get_value(secondResult, '验证x'), get_value(secondResult, '验证y')];

    edgeName = get_text_value(secondResult, '相交边');
    rayT = get_value(secondResult, '射线t');

    targetY = get_value(secondResult, '目标Y');
    verifyY = get_value(secondResult, '验证Y');
    verifyDeltaUV = get_value(secondResult, '验证DeltaUV');
    verifyDeltaY = get_value(secondResult, '验证DeltaY');
    relativeDeltaY = get_value(secondResult, '验证相对DeltaY');

    k1 = get_value(secondResult, 'k1交点到目标');
    k2 = get_value(secondResult, 'k2目标到白点');
    k3 = get_value(secondResult, 'k3交点到白点');
    oneMinusLambda = get_value(secondResult, '一减lambda');
    lambda = get_value(secondResult, 'lambda');

    whitePartY = get_value(secondResult, '白点分量Y');
    pointPartY = get_value(secondResult, '交点分量Y');
    splitSumY = get_value(secondResult, '亮度分解和');
    splitErrorY = get_value(secondResult, '亮度分解误差');

    deltaUVText = format_scientific_value(verifyDeltaUV);
    deltaYText = format_scientific_value(verifyDeltaY);
    relativeDeltaYText = format_scientific_value(relativeDeltaY);
    splitErrorYText = format_scientific_value(splitErrorY);

    whitePWM = get_triplet(secondResult, '白点分解R', '白点分解G', '白点分解B');
    pointPWM = get_triplet(secondResult, '交点分解R', '交点分解G', '交点分解B');
    mixPWM = get_triplet(secondResult, '混合PWM_R', '混合PWM_G', '混合PWM_B');
    backInputPWM = get_triplet(secondResult, '回算输入R', '回算输入G', '回算输入B');

    maxPWM = fixed_max_pwm();

    plot_xy_geometry( ...
        triangleXY, xyY_red, xyY_green, xyY_blue, ...
        whiteXY, targetXY, intersectXY, verifyXY, ...
        edgeName, rayT, ...
        k1, k2, k3, oneMinusLambda, lambda, ...
        targetY, whitePartY, pointPartY, verifyY, ...
        splitSumY, splitErrorY, verifyDeltaUV, verifyDeltaY, relativeDeltaY, maxPWM);

    plot_verify_steps( ...
        whiteXY, targetXY, intersectXY, verifyXY, ...
        targetY, verifyY, verifyDeltaUV, verifyDeltaY, relativeDeltaY, ...
        splitSumY, splitErrorY, ...
        k1, k2, k3, oneMinusLambda, lambda, ...
        whitePartY, pointPartY, ...
        whitePWM, pointPWM, mixPWM, backInputPWM, maxPWM);
end

function plot_xy_geometry(triangleXY, xyY_red, xyY_green, xyY_blue, ...
    whiteXY, targetXY, intersectXY, verifyXY, edgeName, rayT, ...
    k1, k2, k3, oneMinusLambda, lambda, ...
    targetY, whitePartY, pointPartY, verifyY, splitSumY, splitErrorY, ...
    verifyDeltaUV, verifyDeltaY, relativeDeltaY, maxPWM)

    figure('Name', '第2个目标点：xy几何关系', 'Color', 'w', ...
        'Position', [100 100 900 700]);
    hold on;
    grid on;
    axis equal;

    triangleClosed = [triangleXY; triangleXY(1, :)];
    hArea = fill(triangleClosed(:, 1), triangleClosed(:, 2), [0.92 0.95 1.00], ...
        'FaceAlpha', 0.35, 'EdgeColor', 'none');
    hBoundary = plot(triangleClosed(:, 1), triangleClosed(:, 2), 'k-', 'LineWidth', 1.4);

    hWT = plot([whiteXY(1), targetXY(1)], [whiteXY(2), targetXY(2)], ...
        'b-', 'LineWidth', 2.0);
    hTP = plot([targetXY(1), intersectXY(1)], [targetXY(2), intersectXY(2)], ...
        'm-', 'LineWidth', 2.0);
    plot([whiteXY(1), intersectXY(1)], [whiteXY(2), intersectXY(2)], ...
        'k--', 'LineWidth', 0.8);

    plot_point(xyY_red(1:2), 'ro', 'R顶点', [0.010 0.010]);
    plot_point(xyY_green(1:2), 'go', 'G顶点', [0.010 0.010]);
    plot_point(xyY_blue(1:2), 'bo', 'B顶点', [0.010 0.010]);

    plot_point(whiteXY, 'ks', '白点W', [0.010 -0.020]);
    plot_point(targetXY, 'md', '目标T', [0.012 0.000]);
    plot_point(intersectXY, 'cp', '交点P', [0.012 0.000]);
    plot_point(verifyXY, 'yx', '验证V', [0.012 -0.020]);

    label_segment_ratio(whiteXY, targetXY, ...
        sprintf('WT/WP = λ = k2/k3 = %.6f', lambda), [0.010 0.010]);
    label_segment_ratio(targetXY, intersectXY, ...
        sprintf('TP/WP = 1-λ = k1/k3 = %.6f', oneMinusLambda), [0.010 0.010]);

    infoText = sprintf([ ...
        '相交边：%s\n射线t：%.6f\n', ...
        'k1 = %.6f, k2 = %.6f, k3 = %.6f\n', ...
        'λ = %.6f, 1-λ = %.6f\n', ...
        'MaxPWM = %d\n', ...
        '目标Y = %.6f\n白点分量Y = %.6f\n交点分量Y = %.6f\n', ...
        '亮度分解和 = %.6f\n亮度分解误差 = %s\n', ...
        '验证Y = %.6f\n', ...
        'DeltaUV = %s, DeltaY = %s\n', ...
        '相对DeltaY = %s\n', ...
        '回算函数：RGB_to_xyY_32000'], ...
        edgeName, rayT, k1, k2, k3, ...
        lambda, oneMinusLambda, maxPWM, ...
        targetY, whitePartY, pointPartY, splitSumY, splitErrorYText, verifyY, ...
        deltaUVText, deltaYText, relativeDeltaYText);
    text(0.03, 0.97, infoText, 'Units', 'normalized', ...
        'VerticalAlignment', 'top', 'BackgroundColor', 'w', ...
        'EdgeColor', [0.7 0.7 0.7], 'Margin', 6);

    xlabel('x');
    ylabel('y');
    title('第 2 个目标点：白点射线与色域交点');
    legend([hBoundary, hArea, hWT, hTP], ...
        {'色域边界', '色域区域', 'W-T 线段', 'T-P 线段'}, ...
        'Location', 'best');
end

function plot_verify_steps(whiteXY, targetXY, intersectXY, verifyXY, ...
    targetY, verifyY, verifyDeltaUV, verifyDeltaY, relativeDeltaY, ...
    splitSumY, splitErrorY, ...
    k1, k2, k3, oneMinusLambda, lambda, whitePartY, pointPartY, ...
    whitePWM, pointPWM, mixPWM, backInputPWM, maxPWM)

    figure('Name', '第2个目标点：验算步骤', 'Color', 'w', ...
        'Position', [80 60 1380 860]);
    ax = axes();
    axis(ax, 'off');
    hold(ax, 'on');

    modelText = sprintf([ ...
        '1) 先由共线关系求 λ，再拆目标亮度 Y\n\n', ...
        'λ = WT / WP = k2 / k3 = %.6f\n', ...
        '1-λ = TP / WP = k1 / k3 = %.6f\n\n', ...
        '目标 T = (x_T, y_T, Y_T) = (%.4f, %.4f, %.6f)\n', ...
        '白点 W = (x_W, y_W) = (%.4f, %.4f)\n', ...
        '交点 P = (x_P, y_P) = (%.4f, %.4f)\n\n', ...
        'Y_W = Y_T * ((1-λ) * y_W / y_T) = %.6f\n', ...
        'Y_P = Y_T * (λ * y_P / y_T) = %.6f\n', ...
        'Y_W + Y_P = %.6f\n\n', ...
        '2) 当前目录下 xyY_PWM.m 的数学模型\n', ...
        '先求 z = 1 - x - y\n', ...
        '再解 D = M \\ [x; y; z]\n', ...
        'M 的三列分别是：\n%s\n\n', ...
        '然后根据亮度缩放：\n', ...
        'PWM = Y_target / (Y_r*D_r + Y_g*D_g + Y_b*D_b) * MaxPWM * D\n', ...
        '这里 MaxPWM = %d'], ...
        lambda, oneMinusLambda, ...
        targetXY(1), targetXY(2), targetY, ...
        whiteXY(1), whiteXY(2), ...
        intersectXY(1), intersectXY(2), ...
        whitePartY, pointPartY, splitSumY, ...
        formula_matrix_columns(), maxPWM);

    whiteText = sprintf([ ...
        '3) 白点分量 W'' 分解\n', ...
        'W'' = (%.4f, %.4f, %.6f)\n\n', ...
        '%s'], ...
        whiteXY(1), whiteXY(2), whitePartY, ...
        column_vector_text('PWM_W', whitePWM));

    pointText = sprintf([ ...
        '4) 交点分量 P'' 分解\n', ...
        'P'' = (%.4f, %.4f, %.6f)\n\n', ...
        '%s'], ...
        intersectXY(1), intersectXY(2), pointPartY, ...
        column_vector_text('PWM_P', pointPWM));

    mixText = sprintf([ ...
        '5) 两束光的 PWM 逐通道相加\n', ...
        'PWM_mix = PWM_W + PWM_P\n\n', ...
        '%s\n\n', ...
        '回算输入直接使用 0~32000 标尺：\n', ...
        'BackInput = PWM_mix\n\n', ...
        '%s'], ...
        column_vector_text('PWM_mix', mixPWM), ...
        column_vector_text('BackInput', backInputPWM));

    verifyText = sprintf([ ...
        '6) 回算验证\n', ...
        'V = RGB_to_xyY_32000(BackInput) = (%.6f, %.6f, %.6f)\n', ...
        '目标 T = (%.6f, %.6f, %.6f)\n', ...
        '亮度分解和 = %.6f\n', ...
        '亮度分解误差 = %s\n', ...
        'DeltaUV = %s\n', ...
        'DeltaY = %s\n', ...
        '相对DeltaY = %s\n', ...
        'k1 = %.6f,  k2 = %.6f,  k3 = %.6f'], ...
        verifyXY(1), verifyXY(2), verifyY, ...
        targetXY(1), targetXY(2), targetY, ...
        splitSumY, splitErrorYText, ...
        deltaUVText, deltaYText, relativeDeltaYText, ...
        k1, k2, k3);

    draw_box(0.05, 0.68, 0.90, 0.26, modelText, [0.96 0.96 1.00], 12);
    draw_box(0.05, 0.38, 0.42, 0.25, whiteText, [0.96 0.98 1.00], 12);
    draw_box(0.53, 0.38, 0.42, 0.25, pointText, [0.96 1.00 0.96], 12);
    draw_box(0.10, 0.18, 0.80, 0.15, mixText, [1.00 0.98 0.94], 12);
    draw_box(0.10, 0.04, 0.80, 0.10, verifyText, [1.00 0.96 0.96], 12);

    draw_arrow([0.26 0.38], [0.40 0.33]);
    draw_arrow([0.74 0.38], [0.60 0.33]);
    draw_arrow([0.50 0.18], [0.50 0.14]);

    title('第 2 个目标点：λ 亮度分解、xyY\_PWM 分解、RGB\_to\_xyY\_32000 回算', ...
        'FontWeight', 'bold', 'FontSize', 14);
end

function textValue = formula_matrix_columns()
    textValue = sprintf([ ...
        '    col_R = [ (Y_r/y_r)*x_r;  (Y_r/y_r)*y_r;  (Y_r/y_r)*z_r ]\n', ...
        '    col_G = [ (Y_g/y_g)*x_g;  (Y_g/y_g)*y_g;  (Y_g/y_g)*z_g ]\n', ...
        '    col_B = [ (Y_b/y_b)*x_b;  (Y_b/y_b)*y_b;  (Y_b/y_b)*z_b ]']);
end

function value = get_value(tbl, name)
    value = tbl{1, name};
end

function value = get_text_value(tbl, name)
    value = tbl{1, name};
    if iscell(value)
        value = value{1};
    end
    if isstring(value)
        value = char(value);
    end
end

function rgb = get_triplet(tbl, rName, gName, bName)
    rgb = [get_value(tbl, rName), get_value(tbl, gName), get_value(tbl, bName)];
end

function textValue = column_vector_text(name, rgb)
    textValue = sprintf([ ...
        '%s =\n', ...
        '    [ %.6f\n', ...
        '      %.6f\n', ...
        '      %.6f ]'], ...
        name, rgb(1), rgb(2), rgb(3));
end

function plot_point(xy, style, labelText, offset)
    plot(xy(1), xy(2), style, 'LineWidth', 1.8, 'MarkerSize', 9);
    text(xy(1) + offset(1), xy(2) + offset(2), ...
        sprintf('%s (%.4f, %.4f)', labelText, xy(1), xy(2)), ...
        'FontSize', 9, 'FontWeight', 'bold');
end

function label_segment_ratio(p1, p2, labelText, offset)
    mid = (p1 + p2) / 2;
    text(mid(1) + offset(1), mid(2) + offset(2), labelText, ...
        'FontSize', 9, 'FontWeight', 'bold', ...
        'BackgroundColor', 'w', 'EdgeColor', [0.75 0.75 0.75], ...
        'Margin', 4);
end

function draw_box(x, y, w, h, textValue, colorValue, fontSize)
    if nargin < 7
        fontSize = 12;
    end

    annotation('textbox', [x y w h], ...
        'String', textValue, ...
        'FitBoxToText', 'off', ...
        'BackgroundColor', colorValue, ...
        'EdgeColor', [0.35 0.35 0.35], ...
        'LineWidth', 1.0, ...
        'FontName', 'Microsoft YaHei', ...
        'FontSize', fontSize, ...
        'Interpreter', 'none');
end

function draw_arrow(fromPoint, toPoint)
    annotation('arrow', [fromPoint(1), toPoint(1)], [fromPoint(2), toPoint(2)], ...
        'LineWidth', 1.2);
end
