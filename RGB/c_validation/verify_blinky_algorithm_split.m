function [referenceTable, compareTable, summaryTable] = verify_blinky_algorithm_split(csvPath, excelPath)
%VERIFY_BLINKY_ALGORITHM_SPLIT
% Compare BLINKY host C validation output with MATLAB reference results.

    rootDir = fileparts(fileparts(mfilename('fullpath')));
    if exist('default_white_mix_config', 'file') ~= 2
        addpath(rootDir);
    end

    if nargin < 1 || isempty(csvPath)
        csvPath = fullfile(rootDir, 'host_gcc_validation', 'flat_source', ...
            'algorithm_validation_output.csv');
    end
    if ~isfile(csvPath)
        error('verify_blinky_algorithm_split:CsvNotFound', ...
            'CSV not found: %s', csvPath);
    end

    if nargin < 2 || isempty(excelPath)
        excelPath = fullfile(rootDir, 'c_validation', '奥迪30色.xlsx');
    end
    [inputSignals, excelTargetxyY] = read_audi30_excel_inputs(excelPath);
    rawPreview = readtable(csvPath);
    referenceTargetxyY = table2array(rawPreview(:, {'target_x10000', 'target_y10000', 'target_Y10000'})) ./ 10000;

    whiteXY = [0.3152 0.3147];
    verifyPrimaries = [ ...
        0.7038 0.2953 0.7767; ...
        0.1792 0.7356 1.9320; ...
        0.1491 0.0333 0.2253];
    whiteChannelY = 2.2170;
    intersectionTriangleXY = verifyPrimaries(:, 1:2);
    config = default_white_mix_config(intersectionTriangleXY, verifyPrimaries);
    pwmConfig = get_blinky_pwm_config();

    n = size(referenceTargetxyY, 1);
    [insideMask, onMask] = inpolygon( ...
        referenceTargetxyY(:, 1), referenceTargetxyY(:, 2), ...
        config.intersectionTriangleXY(:, 1), ...
        config.intersectionTriangleXY(:, 2));
    insideMask = insideMask | onMask;

    refValid = false(n, 1);
    refWhite = nan(n, 3);
    refPoint = nan(n, 3);
    refLambda = nan(n, 1);
    refOneMinusLambda = nan(n, 1);
    refRayT = nan(n, 1);
    refEdge = strings(n, 1);
    refDeltaUv = nan(n, 1);
    refDeltaY = nan(n, 1);
    refPwm = nan(n, 4);
    refPwmRatio = nan(n, 4);

    for i = 1:n
        step = white_mix_one_target(referenceTargetxyY(i, :), whiteXY, config);
        refValid(i) = step.IsValid;
        refWhite(i, :) = step.WhiteComponent_xyY;
        refPoint(i, :) = step.PointComponent_xyY;
        refLambda(i) = step.Coeff.lambda;
        refOneMinusLambda(i) = step.Coeff.oneMinusLambda;
        refRayT(i) = step.Ray_t;
        refEdge(i) = string(step.Edge);
        refDeltaUv(i) = step.Delta_uv;
        refDeltaY(i) = step.DeltaY;
        [refPwm(i, :), refPwmRatio(i, :)] = compute_blinky_pwm(step, pwmConfig);
    end

    referenceTable = table( ...
        (1:n).', inputSignals.DisplayU, inputSignals.DisplayV, ...
        inputSignals.AlgoU, inputSignals.AlgoV, inputSignals.Intensity10000, ...
        yes_no_text(insideMask), yes_no_text(refValid), ...
        excelTargetxyY(:, 1), excelTargetxyY(:, 2), excelTargetxyY(:, 3), ...
        referenceTargetxyY(:, 1), referenceTargetxyY(:, 2), referenceTargetxyY(:, 3), ...
        refWhite(:, 1), refWhite(:, 2), refWhite(:, 3), ...
        refPoint(:, 1), refPoint(:, 2), refPoint(:, 3), ...
        refEdge, refLambda, refOneMinusLambda, refRayT, ...
        refPwm(:, 1), refPwm(:, 2), refPwm(:, 3), refPwm(:, 4), ...
        refPwmRatio(:, 1), refPwmRatio(:, 2), refPwmRatio(:, 3), refPwmRatio(:, 4), ...
        refDeltaUv, refDeltaY, ...
        'VariableNames', { ...
            'Index', 'DisplayU', 'DisplayV', 'AlgoU', 'AlgoV', 'InputIntensity10000', ...
            'InsideGamutTriangle', 'MatlabValid', ...
            'ExcelTargetX', 'ExcelTargetY', 'ExcelTargetL', ...
            'ReferenceTargetX', 'ReferenceTargetY', 'ReferenceTargetL', ...
            'WhiteX', 'WhiteY', 'WhiteL', ...
            'PointX', 'PointY', 'PointL', ...
            'Edge', 'Lambda', 'OneMinusLambda', 'RayT', ...
            'MatlabPwmR', 'MatlabPwmG', 'MatlabPwmB', 'MatlabPwmW', ...
            'MatlabPwmRatioR', 'MatlabPwmRatioG', 'MatlabPwmRatioB', 'MatlabPwmRatioW', ...
            'VerifyDeltaUV', 'VerifyDeltaY'});

    compareTable = build_compare_table(csvPath, inputSignals, excelTargetxyY, referenceTargetxyY, ...
        insideMask, refValid, refWhite, refPoint, refLambda, ...
        refOneMinusLambda, refRayT, refPwm, refPwmRatio, pwmConfig);

    validBoth = strcmp(compareTable.CValid, "Yes") & strcmp(compareTable.MatlabValid, "Yes");
    summaryTable = table( ...
        n, ...
        sum(insideMask), ...
        sum(~insideMask), ...
        sum(strcmp(compareTable.CValid, "Yes")), ...
        sum(refValid), ...
        sum(validBoth), ...
        sum(strcmp(compareTable.CValid, "Yes") ~= refValid), ...
        max_abs_or_nan(compareTable.WhiteXError(validBoth)), ...
        max_abs_or_nan(compareTable.WhiteYError(validBoth)), ...
        max_abs_or_nan(compareTable.WhiteLError(validBoth)), ...
        max_abs_or_nan(compareTable.PointXError(validBoth)), ...
        max_abs_or_nan(compareTable.PointYError(validBoth)), ...
        max_abs_or_nan(compareTable.PointLError(validBoth)), ...
        max_abs_or_nan(compareTable.TargetXError), ...
        max_abs_or_nan(compareTable.TargetYError), ...
        max_abs_or_nan(compareTable.TargetLError), ...
        max_abs_or_nan(compareTable.LambdaError(validBoth)), ...
        max_abs_or_nan(compareTable.OneMinusLambdaError(validBoth)), ...
        max_abs_or_nan(compareTable.RayTError(validBoth)), ...
        max_abs_or_nan(compareTable.PwmRError(validBoth)), ...
        max_abs_or_nan(compareTable.PwmGError(validBoth)), ...
        max_abs_or_nan(compareTable.PwmBError(validBoth)), ...
        max_abs_or_nan(compareTable.PwmWError(validBoth)), ...
        'VariableNames', { ...
            'TotalCount', 'InsideGamutTriangleCount', 'OutsideGamutTriangleCount', ...
            'CValidCount', 'MatlabValidCount', 'ValidBothCount', 'ValidMismatchCount', ...
            'MaxWhiteXError', 'MaxWhiteYError', 'MaxWhiteLError', ...
            'MaxPointXError', 'MaxPointYError', 'MaxPointLError', ...
            'MaxTargetXError', 'MaxTargetYError', 'MaxTargetLError', ...
            'MaxLambdaError', 'MaxOneMinusLambdaError', 'MaxRayTError', ...
            'MaxPwmRError', 'MaxPwmGError', 'MaxPwmBError', 'MaxPwmWError'});

    if nargout == 0
        fprintf('\nBLINKY Algorithm.c validation:\n');
        fprintf('White point: (%.4f, %.4f)\n', whiteXY(1), whiteXY(2));
        fprintf('White channel Y: %.4f\n', whiteChannelY);
        fprintf('Excel: %s\n', excelPath);
        fprintf('CSV: %s\n', csvPath);
        show_blinky_validation_window(compareTable, summaryTable, referenceTargetxyY, insideMask, config, whiteXY, csvPath, excelPath);
        disp(summaryTable);
        disp(compareTable);
    end
end

function compareTable = build_compare_table(csvPath, inputSignals, excelTargetxyY, referenceTargetxyY, ...
