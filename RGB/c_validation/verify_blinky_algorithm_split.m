            'PwmRatioRError', 'PwmRatioGError', 'PwmRatioBError', 'PwmRatioWError'});
end

function pwmConfig = get_blinky_pwm_config()
    pwmConfig = struct();
    pwmConfig.PwmPeriod = 32000;
    pwmConfig.Factor = hex2dec('8000');
    pwmConfig.BrightnessFactor = 100;
    pwmConfig.TempAdjust = 100 * 2^6;
    pwmConfig.WhiteXY = [0.3152 0.3147];

    redY20 = floor(7767 / 20);
    greenY20 = floor(19320 / 20);
    blueY20 = floor(2253 / 20);
    whiteY20 = floor(22170 / 20);

    pwmConfig.CurrentRed = [0.7038, 0.2953, redY20 / 10000 * 7.5];
    pwmConfig.CurrentGreen = [0.1792, 0.7356, greenY20 / 10000 * 7.5];
    pwmConfig.CurrentBlue = [0.1491, 0.0333, blueY20 / 10000 * 7.5];
    pwmConfig.CurrentWhiteY = whiteY20 / 10000 * 7.5;
end

function [pwmValues, pwmRatios] = compute_blinky_pwm(step, cfg)
    if step.IsValid
        dutyColor = step.PointComponent_xyY;
        whiteColor = step.WhiteComponent_xyY;
    else
        dutyColor = step.Target_xyY;
        whiteColor = [cfg.WhiteXY, 0];
    end

    [pwmR, pwmG, pwmB] = compute_rgb_pwm(dutyColor, cfg);
    pwmW = compute_white_pwm(whiteColor, cfg);

    pwmValues = [pwmR, pwmG, pwmB, pwmW];
    pwmRatios = pwmValues / cfg.PwmPeriod;
end

function [pwmR, pwmG, pwmB] = compute_rgb_pwm(colorxyY, cfg)
    x = colorxyY(1);
    y = colorxyY(2);
    Y = colorxyY(3);

    red = cfg.CurrentRed;
    green = cfg.CurrentGreen;
    blue = cfg.CurrentBlue;

    a = x - blue(1);
    d = y - blue(2);
    Bm = blue(3) / blue(2);

    b = green(2) - y;
    c = green(1) - x;
    Gm = green(3) / green(2);

    e = red(1) - x;
    f = red(2) - y;
    Rm = red(3) / red(2);

    R_all = a * b - c * d;
    B_all = e * b - c * f;
    G_all = d * e - f * a;

    duty_r = Bm * Gm * R_all;
    duty_g = Rm * Bm * G_all;
    duty_b = Rm * Gm * B_all;

    mixY = compute_mix_y(Y, cfg.TempAdjust);
    denominator = red(3) * duty_r + green(3) * duty_g + blue(3) * duty_b;

    if denominator <= 0 || mixY <= 0
        pwmR = 0;
        pwmG = 0;
        pwmB = 0;
        return;
    end

    scale = mixY / denominator;
    duty_r = clamp01(duty_r * scale);
    duty_g = clamp01(duty_g * scale);
    duty_b = clamp01(duty_b * scale);

    pwmR = scale_pwm_count(duty_r, cfg);
    pwmG = scale_pwm_count(duty_g, cfg);
    pwmB = scale_pwm_count(duty_b, cfg);
end

function pwmW = compute_white_pwm(whitexyY, cfg)
    mixY = compute_mix_y(whitexyY(3), cfg.TempAdjust);
    if mixY <= 0 || cfg.CurrentWhiteY <= 0
        pwmW = 0;
        return;
    end

    duty = clamp01(mixY / cfg.CurrentWhiteY);
    pwmW = scale_pwm_count(duty, cfg);
end

function mixY = compute_mix_y(Y, tempAdjust)
    mixY = Y * floor(tempAdjust / 2);
    mixY = mixY * 0.02;
    mixY = mixY * 0.015625;
end

function pwm = scale_pwm_count(duty, cfg)
    pwm = floor(duty * cfg.PwmPeriod);
    pwm = floor(pwm * bitshift(cfg.Factor, -7) / 256);
    pwm = floor(pwm * bitand(cfg.BrightnessFactor, 127) / 100);
    pwm = max(min(pwm, 32767), 0);
end

function value = clamp01(value)
    value = min(max(value, 0), 1);
end

