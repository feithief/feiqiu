function out = yes_no_text(mask)
    out = repmat("No", numel(mask), 1);
    out(logical(mask)) = "Yes";
end

function value = max_abs_or_nan(data)
    data = data(isfinite(data));
    if isempty(data)
        value = NaN;
    else
        value = max(abs(data(:)));
    end
end

function data = sanitize_uitable_data(data)
    for i = 1:numel(data)
        if isstring(data{i})
            data{i} = char(data{i});
        end
    end
end

