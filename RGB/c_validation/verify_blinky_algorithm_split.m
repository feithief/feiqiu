    cPwmError = double(cPwm) - refPwm(1:n, :);
    cPwmRatioError = cPwmRatio - refPwmRatio(1:n, :);

    compareTable = table( ...
        cIndex, cDisplayU, cDisplayV, cAlgoU, cAlgoV, cInputIntensity, ...
        yes_no_text(insideMask(1:n)), yes_no_text(cValid), yes_no_text(refValid(1:n)), ...
        excelTargetxyY(1:n, 1), excelTargetxyY(1:n, 2), excelTargetxyY(1:n, 3), ...
        cTarget(:, 1), cTarget(:, 2), cTarget(:, 3), ...
        cTargetError(:, 1), cTargetError(:, 2), cTargetError(:, 3), ...
        cWhite(:, 1), cWhite(:, 2), cWhite(:, 3), ...
        refWhite(1:n, 1), refWhite(1:n, 2), refWhite(1:n, 3), ...
        cWhiteError(:, 1), cWhiteError(:, 2), cWhiteError(:, 3), ...
        cPoint(:, 1), cPoint(:, 2), cPoint(:, 3), ...
        refPoint(1:n, 1), refPoint(1:n, 2), refPoint(1:n, 3), ...
        cPointError(:, 1), cPointError(:, 2), cPointError(:, 3), ...
        cLambda, refLambda(1:n), cLambdaError, ...
        cOneMinusLambda, refOneMinusLambda(1:n), cOneMinusLambdaError, ...
        cRayT, refRayT(1:n), cRayTError, ...
        cPwm(:, 1), cPwm(:, 2), cPwm(:, 3), cPwm(:, 4), ...
        refPwm(1:n, 1), refPwm(1:n, 2), refPwm(1:n, 3), refPwm(1:n, 4), ...
        cPwmError(:, 1), cPwmError(:, 2), cPwmError(:, 3), cPwmError(:, 4), ...
        cPwmRatio(:, 1), cPwmRatio(:, 2), cPwmRatio(:, 3), cPwmRatio(:, 4), ...
        refPwmRatio(1:n, 1), refPwmRatio(1:n, 2), refPwmRatio(1:n, 3), refPwmRatio(1:n, 4), ...
        cPwmRatioError(:, 1), cPwmRatioError(:, 2), cPwmRatioError(:, 3), cPwmRatioError(:, 4), ...
        'VariableNames', { ...
            'Index', 'DisplayU', 'DisplayV', 'AlgoU', 'AlgoV', 'InputIntensity10000', ...
            'InsideGamutTriangle', 'CValid', 'MatlabValid', ...
            'ExcelTargetX', 'ExcelTargetY', 'ExcelTargetL', ...
            'CTargetX', 'CTargetY', 'CTargetL', ...
            'TargetXError', 'TargetYError', 'TargetLError', ...
            'CWhiteX', 'CWhiteY', 'CWhiteL', 'MatlabWhiteX', 'MatlabWhiteY', 'MatlabWhiteL', ...
            'WhiteXError', 'WhiteYError', 'WhiteLError', ...
            'CPointX', 'CPointY', 'CPointL', 'MatlabPointX', 'MatlabPointY', 'MatlabPointL', ...
