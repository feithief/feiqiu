    refPwm, refPwmRatio, pwmConfig)

    requiredColumns = { ...
        'index', 'display_u', 'display_v', 'algo_u', 'algo_v', 'input_intensity10000', ...
        'target_x10000', 'target_y10000', 'target_Y10000', 'valid', ...
        'white_x10000', 'white_y10000', 'white_Y10000', ...
        'point_x10000', 'point_y10000', 'point_Y10000', ...
        'edge_index', 'lambda_fix16', 'one_minus_lambda_fix16', 'ray_t_fix16', ...
        'pwm_r', 'pwm_g', 'pwm_b', 'pwm_w'};

    rawTable = readtable(csvPath);
    missingColumns = requiredColumns(~ismember(requiredColumns, rawTable.Properties.VariableNames));
    if ~isempty(missingColumns)
        error('verify_blinky_algorithm_split:MissingColumns', ...
            'CSV is missing required columns: %s', strjoin(missingColumns, ', '));
    end

    n = height(rawTable);
    if size(referenceTargetxyY, 1) < n || size(excelTargetxyY,1) < n
        error('verify_blinky_algorithm_split:TargetCountMismatch', ...
            'MATLAB target list has fewer rows than CSV: excel=%d, ref=%d, csv=%d.', ...
            size(excelTargetxyY, 1), size(referenceTargetxyY, 1), n);
    end

    cIndex = rawTable.index;
    cDisplayU = rawTable.display_u;
    cDisplayV = rawTable.display_v;
    cAlgoU = rawTable.algo_u;
    cAlgoV = rawTable.algo_v;
    cInputIntensity = rawTable.input_intensity10000;
    cTarget = table2array(rawTable(:, {'target_x10000', 'target_y10000', 'target_Y10000'})) ./ 10000;
    cWhite = table2array(rawTable(:, {'white_x10000', 'white_y10000', 'white_Y10000'})) ./ 10000;
    cPoint = table2array(rawTable(:, {'point_x10000', 'point_y10000', 'point_Y10000'})) ./ 10000;
