/*!< Max length of serial Number >*/
#define DMAX_SERIAL_NUMBER_LENGTH (23U)
/*!< Max length of part NOumber >*/
#define DMAX_PART_NUMBER_LENGTH   (11U)
/*!< Hardware section length >*/
#define DHARDWARE_VERSION_LENGTH  (3U)
/*!< Flash is free for updating >*/
#define	FLASH_UPDATE_FREE			0x0		
/*!< Flash's memory updating is on process >*/
#define	FLASH_UPDATE_PROCESSING		0x1		
/*!< Flash's memory has been locked >*/
#define FLASH_UPDATE_LOCKED			0x80


/*!< This ENUM indicates which e_Platform we are using >*/
typedef enum
{
	E_PLATFORM_TYPE_MQB        = 0x0000, /*!< MQB e_Platform >*/
	E_PLATFORM_TYPE_MLBEVO     = 0x0001, /*!< MLBevo e_Platform >*/
	E_PLATFORM_TYPE_MLBEVOVW   = 0x0002, /*!< MLBevoVW e_Platform >*/
	E_PLATFORM_TYPE_MAX        = 0xFFFF, /*!< To make this ENUM's size equals two >*/
} E_PLATFORM_TYPE;


/*!< This structure contains product information >*/
typedef struct
{
	uint8_t au8_buf[18];	/*!< The buffer to store product information. >*/
}ST_LINE_CONTENT;

typedef enum HardwareType
{  
  E_HARDWARE_TYPE_NOCAP = 0x11,
  E_HARDWARE_TYPE_Cap   = 0x1A,
}E_HARDWARE_TYPE;
  
/*!< This structure contains flash memory >*/
typedef struct
{
	uint16_t       	u16_Crc;         /*!< Flash content crc16 result >*/
	uint16_t       	u16_MagicNO;     /*!< magic no also using as version flag >*/
	/*The old version this section has two bytes, we add two reserved bytes to prevent overflow >*/
	E_PLATFORM_TYPE e_Platform;		/*!< Platform information @EPlatformType.*/

	uint16_t       	u16_LedSupplier; /*!< led supplier using as lock functions and other special functions >*/
	uint16_t       	u16_Redx;        /*!< Current led red CIE x coordinate >*/
	uint16_t       	u16_Redy;        /*!< Current led red CIE y coordinate >*/
	uint32_t      	u32_RedY;        /*!< Current led red CIE Y coordinate >*/
	uint16_t       	u16_Greenx;      /*!< Current led green CIE x coordinate >*/
	uint16_t       	u16_Greeny;      /*!< Current led green CIE y coordinate >*/
	uint32_t       	u32_GreenY;      /*!< Current led green CIE Y coordinate >*/
	uint16_t       	u16_Bluex;       /*!< Current led blue CIE x coordinate >*/
	uint16_t       	u16_Bluey;       /*!< Current led blue CIE y coordinate >*/
	uint32_t       	u32_BlueY;       /*!< Current led blue CIE Y coordinate >*/
	uint16_t       	u16_Factor;      /*!< Customor uses this member to adjust RGB light intensity >*/
  
	uint8_t        	au8_PartNo[DMAX_PART_NUMBER_LENGTH+1];              /*!< part number, add one byte for '\0' >*/
	uint8_t        	au8_HardwareVersion[DHARDWARE_VERSION_LENGTH+1];    /*!< hardware version, add one byte for '\0' >*/
	uint16_t       	u16_GroupAddr;   		/*!< this member contains this RGB module's group address >*/
	uint16_t       	u16_SingleAddr;  		/*!< this member contains this RGB module's single address >*/
	uint8_t        	au8_SerialNo[DMAX_SERIAL_NUMBER_LENGTH+1];          /*!< serial number, add one byte for '\0' >*/
	int16_t        	s16_RThermolRatio;		/*!< Thermal ratio of red led >*/
	int16_t        	s16_GThermolRatio;		/*!< Thermal ratio of green led >*/
	int16_t        	s16_BThermolRatio;		/*!< Thermal ratio of blue led >*/
	int16_t        	s16_McuThermolRatio;	/*!< Thermal ratio of MCU >*/
	int8_t         	s8_RatingLowerVoltage;  /*!< Compensation for low voltage >*/
	int8_t         	s8_RatingHigherVoltage; /*!< Compensation for High voltage >*/
	uint8_t        	u8_RCapCompensate;      /*!< Compensation for PWM lost causing by capacitor >*/
	uint8_t        	u8_GCapCompensate;      /*!< Compensation for PWM lost causing by capacitor >*/
	uint8_t        	u8_BCapCompensate;      /*!< TCompensation for PWM lost causing by capacitor >*/
	uint8_t        	au8_ProductID[5];		/*!< supplier, function ,variant ID >*/
	uint16_t		u16_Cali_Volt;		/*!< Voltage for calibration >*/
	uint16_t		u16_TamperCount;		/*!< The count of falsh has been tampered with >*/
	uint16_t		u16_Diag2ECount;		/*!< The count of diagnostic modifications using 2E >*/
	uint16_t		u16_CaliTemp;		/*!< temperature for calibration	 >*/
	uint16_t		u16_VoltCaliflag;		/*!< sed to verify whether the voltage is complete >*/
	E_HARDWARE_TYPE		e_HardwareType;		/*!< flag hardware type RLN211 or RLN211A. >*/
	uint8_t		u8_DebugSwitch[3];
	uint8_t		u8_WriteCompleteFlag;

}ST_FLASH_CONTENT;


