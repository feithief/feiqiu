                     'MenuBar', 'none', ...
                     'ToolBar', 'none', ...
                     'Color', [0.96, 0.96, 0.96], ...
                     'Position', [70, 80, 1550, 740]);

        uicontrol('Parent', fig, ...
            'Style', 'text', ...
            'String', '当前模型Ra数值表：精确法 / 投影1点 / 投影K点 / 纯RGB', ...
            'Units', 'normalized', ...
            'Position', [0.015, 0.94, 0.97, 0.045], ...
