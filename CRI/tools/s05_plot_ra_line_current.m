                  'String', '当前模型Ra结果（可复制）', ...
                  'Units', 'normalized', ...
                  'Position', [0.03, 0.94, 0.94, 0.04], ...
                  'FontSize', 11, ...
                  'FontWeight', 'bold', ...
                  'HorizontalAlignment', 'left');

        uicontrol('Parent', d, ...
                  'Style', 'edit', ...
                  'String', resultText, ...
                  'Units', 'normalized', ...
                  'Position', [0.03, 0.10, 0.94, 0.83], ...
                  'Max', 2, ...
                  'Min', 0, ...
                  'HorizontalAlignment', 'left', ...
                  'FontName', 'Consolas', ...
                  'FontSize', 10);

        uicontrol('Parent', d, ...
                  'Style', 'pushbutton', ...
                  'String', '关闭', ...
                  'Units', 'normalized', ...
