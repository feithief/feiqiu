static uint16_t RatioK_GetU(uint32_t packedValue)
{
    return (uint16_t)(packedValue & ALGO_RATIO_K_U_MASK);
}

static uint16_t RatioK_GetV(uint32_t packedValue)
{
    return (uint16_t)((packedValue & ALGO_RATIO_K_V_MASK) >> ALGO_RATIO_K_V_SHIFT);
}

static uint16_t RatioK_GetRatio12(uint32_t packedValue)
{
    return (uint16_t)((packedValue & ALGO_RATIO_K_RATIO_MASK) >> ALGO_RATIO_K_RATIO_SHIFT);
}

static uint16_t RatioK_ConvertRatio12ToQ10000(uint16_t ratio12)
{
    uint32_t ratioQ10000;

    ratioQ10000 = (((uint32_t)ratio12 * ALGO_RATIO_K_RATIO_Q10000_MAX) +
                   (ALGO_RATIO_K_RATIO12_MAX / 2u)) /
                  ALGO_RATIO_K_RATIO12_MAX;

    if (ratioQ10000 > ALGO_RATIO_K_RATIO_Q10000_MAX)
    {
        ratioQ10000 = ALGO_RATIO_K_RATIO_Q10000_MAX;
    }

    return (uint16_t)ratioQ10000;
}

static uint32_t RatioK_CalcDistance2(uint16_t u1, uint16_t v1, uint16_t u2, uint16_t v2)
{
    int32_t du;
    int32_t dv;

    du = (int32_t)u1 - (int32_t)u2;
    dv = (int32_t)v1 - (int32_t)v2;

    return (uint32_t)((du * du) + (dv * dv));
}

static uint16_t RatioK_DivRoundU32(uint32_t numerator, uint32_t denominator)
{
    if (denominator == 0u)
    {
        return 0u;
    }

    return (uint16_t)((numerator + (denominator / 2u)) / denominator);
}

static RatioKResult RatioK_GetWhiteRatio(uint16_t targetU, uint16_t targetV, uint8_t kAmount, uint8_t useWeight)
{
    RatioKResult result;
    uint32_t nearestDistance[ALGO_RATIO_K_MAX_K];
    uint16_t nearestRatio12[ALGO_RATIO_K_MAX_K];

    uint16_t lutIndex;
    uint16_t pointU;
    uint16_t pointV;
    uint16_t pointRatio12;
    uint32_t packedValue;
    uint32_t distance2;

    uint8_t insertIndex;
    uint8_t shiftIndex;
    uint8_t nearestCount;
    uint8_t i;

    uint32_t weight;
    uint32_t weightSum;
    uint32_t weightedRatioSum;
    uint32_t ratioSum;

    uint16_t pointRatioQ10000;
    uint16_t ratioResult;

    result.valid = 0u;
    result.whiteRatioQ10000 = 0u;
    result.whiteRatio = 0.0;
    result.rgbRatio = 0.0;
    result.kUsed = 0u;

    if (kAmount == 0u)
    {
        return result;
    }

    if (kAmount > ALGO_RATIO_K_MAX_K)
    {
        kAmount = ALGO_RATIO_K_MAX_K;
    }

    for (i = 0u; i < kAmount; i++)
    {
        nearestDistance[i] = ALGO_RATIO_K_DISTANCE_MAX;
        nearestRatio12[i] = 0u;
    }

    nearestCount = 0u;

    for (lutIndex = 0u; lutIndex < ALGO_RATIO_K_LUT_COUNT; lutIndex++)
    {
        packedValue = g_algoRatioKPackedLut[lutIndex];

        pointU = RatioK_GetU(packedValue);
        pointV = RatioK_GetV(packedValue);
        pointRatio12 = RatioK_GetRatio12(packedValue);

        distance2 = RatioK_CalcDistance2(targetU, targetV, pointU, pointV);

        if (distance2 == 0u)
        {
            result.whiteRatioQ10000 = RatioK_ConvertRatio12ToQ10000(pointRatio12);
            result.whiteRatio = (double)result.whiteRatioQ10000 / 10000.0;
            result.rgbRatio = 1.0 - result.whiteRatio;
            result.kUsed = 1u;
            result.valid = 1u;
            return result;
        }

        for (insertIndex = 0u; insertIndex < kAmount; insertIndex++)
        {
            if (distance2 < nearestDistance[insertIndex])
            {
                for (shiftIndex = (uint8_t)(kAmount - 1u); shiftIndex > insertIndex; shiftIndex--)
                {
                    nearestDistance[shiftIndex] = nearestDistance[shiftIndex - 1u];
                    nearestRatio12[shiftIndex] = nearestRatio12[shiftIndex - 1u];
                }

                nearestDistance[insertIndex] = distance2;
                nearestRatio12[insertIndex] = pointRatio12;

                if (nearestCount < kAmount)
                {
                    nearestCount++;
                }

                break;
            }
        }
    }

    if (nearestCount == 0u)
    {
        return result;
    }

    if (useWeight != 0u)
    {
        weightSum = 0u;
        weightedRatioSum = 0u;

        for (i = 0u; i < nearestCount; i++)
        {
            pointRatioQ10000 = RatioK_ConvertRatio12ToQ10000(nearestRatio12[i]);

            weight = (uint32_t)(ALGO_RATIO_K_WEIGHT_SCALE / (nearestDistance[i] + 1u));

            if (weight == 0u)
            {
                weight = 1u;
            }

            weightedRatioSum += ((uint32_t)pointRatioQ10000 * weight);
            weightSum += weight;
        }

        ratioResult = RatioK_DivRoundU32(weightedRatioSum, weightSum);
    }
    else
    {
        ratioSum = 0u;

        for (i = 0u; i < nearestCount; i++)
        {
            pointRatioQ10000 = RatioK_ConvertRatio12ToQ10000(nearestRatio12[i]);
            ratioSum += (uint32_t)pointRatioQ10000;
        }

        ratioResult = RatioK_DivRoundU32(ratioSum, nearestCount);
    }

    if (ratioResult > ALGO_RATIO_K_RATIO_Q10000_MAX)
    {
        ratioResult = ALGO_RATIO_K_RATIO_Q10000_MAX;
    }

    result.whiteRatioQ10000 = ratioResult;
    result.whiteRatio = (double)ratioResult / 10000.0;
    result.rgbRatio = 1.0 - result.whiteRatio;
    result.kUsed = nearestCount;
    result.valid = 1u;

    return result;
}

