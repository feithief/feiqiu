static void Uv1976ToXy(double u, double v, double *x, double *y)
{
    double den;

    den = 6.0 * u - 16.0 * v + 12.0;

    if (fabs(den) < 1e-12)
    {
        *x = 0.0;
        *y = 0.0;
    }
    else
    {
        *x = 9.0 * u / den;
        *y = 4.0 * v / den;
    }
}

static void XyYToXYZ(CiePoint p, double *X, double *Y, double *Z)
{
    if (fabs(p.y) < 1e-12)
    {
        *X = 0.0;
        *Y = 0.0;
        *Z = 0.0;
        return;
    }

    *X = p.x * p.Y / p.y;
    *Y = p.Y;
    *Z = (1.0 - p.x - p.y) * p.Y / p.y;
}

static double Det3(double a11, double a12, double a13,
                   double a21, double a22, double a23,
                   double a31, double a32, double a33)
{
    return a11 * (a22 * a33 - a23 * a32)
         - a12 * (a21 * a33 - a23 * a31)
         + a13 * (a21 * a32 - a22 * a31);
}

static RgbWeight SolveRgbWeight(CiePoint r, CiePoint g, CiePoint b, CiePoint target)
{
    RgbWeight w;
    double rX, rY, rZ;
    double gX, gY, gZ;
    double bX, bY, bZ;
    double tX, tY, tZ;
    double detM;

    w.r = 0.0;
    w.g = 0.0;
    w.b = 0.0;
    w.valid = 0u;

    XyYToXYZ(r, &rX, &rY, &rZ);
    XyYToXYZ(g, &gX, &gY, &gZ);
    XyYToXYZ(b, &bX, &bY, &bZ);
    XyYToXYZ(target, &tX, &tY, &tZ);

    detM = Det3(rX, gX, bX,
                rY, gY, bY,
                rZ, gZ, bZ);

    if (fabs(detM) < 1e-12)
    {
        return w;
    }

    w.r = Det3(tX, gX, bX,
               tY, gY, bY,
               tZ, gZ, bZ) / detM;

    w.g = Det3(rX, tX, bX,
               rY, tY, bY,
               rZ, tZ, bZ) / detM;

    w.b = Det3(rX, gX, tX,
               rY, gY, tY,
               rZ, gZ, tZ) / detM;

    w.valid = 1u;

    return w;
}

static void AppendText(char *dst, size_t dstSize, const char *fmt, ...)
{
    va_list args;
    size_t len;

    len = strlen(dst);

    if (len >= dstSize)
    {
        return;
    }

    va_start(args, fmt);
    vsnprintf(dst + len, dstSize - len, fmt, args);
    va_end(args);
}

static void CalculateAndShow(HWND hwnd)
{
    double inputU;
    double inputV;
    double targetU;
    double targetV;
    uint16_t targetU1000;
    uint16_t targetV1000;

    double targetX;
    double targetYxy;
    double targetLum;

    int kAmount;
    int useWeight;
    int pwmMax;

    CiePoint whitePoint;
    CiePoint splitWhite;
    CiePoint splitRgb;
    CiePoint redPoint;
    CiePoint greenPoint;
    CiePoint bluePoint;

    RatioKResult ratioResult;
    RgbWeight rgbWeight;

    double ratioFactor;
    double lambda;
    double rayT;
    double dirX;
    double dirY;
    double rawWhiteRatio;
    double maxWhiteRatioByY;
    uint8_t whiteRatioClamped;

    int pwmR;
    int pwmG;
    int pwmB;
    int pwmW;

    char resultText[12000];

    inputU = GetDlgDouble(hwnd, IDC_U_INPUT, 40.0);
    inputV = GetDlgDouble(hwnd, IDC_V_INPUT, 94.0);
    targetLum = GetDlgDouble(hwnd, IDC_Y_INPUT, 3.0);

    /*
     * Engineering input:
     *   40 / 94 -> 200 / 470 -> 0.200 / 0.470
     */
    if (inputU > 1.0)
    {
        targetU1000 = (uint16_t)RoundToInt(inputU * 5.0);
        targetU = (double)targetU1000 / 1000.0;
    }
    else
    {
        targetU = inputU;
        targetU1000 = (uint16_t)RoundToInt(targetU * 1000.0);
    }

    if (inputV > 1.0)
    {
        targetV1000 = (uint16_t)RoundToInt(inputV * 5.0);
        targetV = (double)targetV1000 / 1000.0;
    }
    else
    {
        targetV = inputV;
        targetV1000 = (uint16_t)RoundToInt(targetV * 1000.0);
    }

    Uv1976ToXy(targetU, targetV, &targetX, &targetYxy);

    kAmount = ClampInt(GetDlgIntSafe(hwnd, IDC_K_INPUT, 6), 1, (int)ALGO_RATIO_K_MAX_K);
    useWeight = (int)SendDlgItemMessageA(hwnd, IDC_WEIGHT_ENABLE, BM_GETCHECK, 0, 0);
    pwmMax = ClampInt(GetDlgIntSafe(hwnd, IDC_PWM_MAX, 255), 1, 65535);

    whitePoint.x = GetDlgDouble(hwnd, IDC_WHITE_X, 0.2810);
    whitePoint.y = GetDlgDouble(hwnd, IDC_WHITE_Y, 0.2900);
    whitePoint.Y = GetDlgDouble(hwnd, IDC_WHITE_YMAX, 21.5);

    redPoint.x = GetDlgDouble(hwnd, IDC_R_X, 0.6250);
    redPoint.y = GetDlgDouble(hwnd, IDC_R_Y, 0.3420);
    redPoint.Y = GetDlgDouble(hwnd, IDC_R_YMAX, 15.8);

    greenPoint.x = GetDlgDouble(hwnd, IDC_G_X, 0.3270);
    greenPoint.y = GetDlgDouble(hwnd, IDC_G_Y, 0.5280);
    greenPoint.Y = GetDlgDouble(hwnd, IDC_G_YMAX, 17.8);

    bluePoint.x = GetDlgDouble(hwnd, IDC_B_X, 0.1770);
    bluePoint.y = GetDlgDouble(hwnd, IDC_B_Y, 0.0990);
    bluePoint.Y = GetDlgDouble(hwnd, IDC_B_YMAX, 13.1);

    ratioResult = RatioK_GetWhiteRatio(targetU1000, targetV1000, (uint8_t)kAmount, (uint8_t)useWeight);

    rawWhiteRatio = ratioResult.whiteRatio;
    maxWhiteRatioByY = 1.0;
    whiteRatioClamped = 0u;

    resultText[0] = '\0';

    AppendText(resultText, sizeof(resultText), "================ K-Ratio RGBW GUI Result ================\r\n");
    AppendText(resultText, sizeof(resultText), "Raw input: Uin = %.6f, Vin = %.6f\r\n", inputU, inputV);
    AppendText(resultText, sizeof(resultText), "Algorithm input: U = %u, V = %u  ->  u' = %.6f, v' = %.6f\r\n", targetU1000, targetV1000, targetU, targetV);
    AppendText(resultText, sizeof(resultText), "Converted xyY: x = %.6f, y = %.6f, Y = %.6f\r\n", targetX, targetYxy, targetLum);
    AppendText(resultText, sizeof(resultText), "K = %d, Weight = %s, LUT Count = %u\r\n\r\n", kAmount, useWeight ? "ON" : "OFF", ALGO_RATIO_K_LUT_COUNT);

    if (ratioResult.valid == 0u)
    {
        AppendText(resultText, sizeof(resultText), "K-ratio LUT lookup failed.\r\n");
        SetWindowTextA(g_hwndResult, resultText);
        return;
    }

    if (fabs(whitePoint.y) < 1e-12)
    {
        AppendText(resultText, sizeof(resultText), "RGB mixed point failed: whitePoint.y is too small.\r\n");
        SetWindowTextA(g_hwndResult, resultText);
        return;
    }

    if (fabs(targetYxy) > 1e-12)
    {
        /*
         * Keep lambda positive:
         *   lambda = 1 - whiteRatio * target_y / white_y
         * Therefore:
         *   whiteRatio < white_y / target_y
         *
         * This GUI clamp is only for desktop display. The ECU branch should use
         * the original Algorithm.c boundary clamp when available.
         */
        maxWhiteRatioByY = (whitePoint.y / targetYxy) - 0.000001;

        if (maxWhiteRatioByY < 0.0)
        {
            maxWhiteRatioByY = 0.0;
        }

        if (maxWhiteRatioByY > 1.0)
        {
            maxWhiteRatioByY = 1.0;
        }

        if (ratioResult.whiteRatio > maxWhiteRatioByY)
        {
            ratioResult.whiteRatio = maxWhiteRatioByY;
            ratioResult.whiteRatioQ10000 = (uint16_t)ClampInt(RoundToInt(ratioResult.whiteRatio * 10000.0), 0, 10000);
            ratioResult.rgbRatio = 1.0 - ratioResult.whiteRatio;
            whiteRatioClamped = 1u;
        }
    }

    splitWhite.x = whitePoint.x;
    splitWhite.y = whitePoint.y;
    splitWhite.Y = targetLum * ratioResult.whiteRatio;

    ratioFactor = ratioResult.whiteRatio * targetYxy / whitePoint.y;
    lambda = 1.0 - ratioFactor;

    if (lambda <= 1e-12)
    {
        AppendText(resultText, sizeof(resultText), "RGB mixed point failed: lambda is invalid.\r\n");
        SetWindowTextA(g_hwndResult, resultText);
        return;
    }

    rayT = 1.0 / lambda;
    dirX = targetX - whitePoint.x;
    dirY = targetYxy - whitePoint.y;

    splitRgb.x = whitePoint.x + rayT * dirX;
    splitRgb.y = whitePoint.y + rayT * dirY;
    splitRgb.Y = targetLum * ratioResult.rgbRatio;

    rgbWeight = SolveRgbWeight(redPoint, greenPoint, bluePoint, splitRgb);

    if (rgbWeight.valid != 0u)
    {
        pwmR = ClampInt(RoundToInt(rgbWeight.r * (double)pwmMax), 0, pwmMax);
        pwmG = ClampInt(RoundToInt(rgbWeight.g * (double)pwmMax), 0, pwmMax);
        pwmB = ClampInt(RoundToInt(rgbWeight.b * (double)pwmMax), 0, pwmMax);
    }
    else
    {
        pwmR = 0;
        pwmG = 0;
        pwmB = 0;
    }

    if (whitePoint.Y > 1e-12)
    {
        pwmW = ClampInt(RoundToInt((splitWhite.Y / whitePoint.Y) * (double)pwmMax), 0, pwmMax);
    }
    else
    {
        pwmW = ClampInt(RoundToInt(ratioResult.whiteRatio * (double)pwmMax), 0, pwmMax);
    }

    AppendText(resultText, sizeof(resultText), "---------------- K-Ratio LUT Result ----------------\r\n");
    AppendText(resultText, sizeof(resultText), "valid              = %u\r\n", ratioResult.valid);
    AppendText(resultText, sizeof(resultText), "kUsed              = %u\r\n", ratioResult.kUsed);
    AppendText(resultText, sizeof(resultText), "whiteRatioQ10000   = %u\r\n", ratioResult.whiteRatioQ10000);
    AppendText(resultText, sizeof(resultText), "rawWhiteRatio      = %.6f\r\n", rawWhiteRatio);
    AppendText(resultText, sizeof(resultText), "usedWhiteRatio     = %.6f\r\n", ratioResult.whiteRatio);
    AppendText(resultText, sizeof(resultText), "maxWhiteRatioByY   = %.6f\r\n", maxWhiteRatioByY);
    AppendText(resultText, sizeof(resultText), "whiteRatioClamped  = %u\r\n", whiteRatioClamped);
    AppendText(resultText, sizeof(resultText), "rgbRatio           = %.6f\r\n\r\n", ratioResult.rgbRatio);

    AppendText(resultText, sizeof(resultText), "---------------- White Output Point splitWhiteCIE ----------------\r\n");
    AppendText(resultText, sizeof(resultText), "splitWhiteCIE.x    = %.6f\r\n", splitWhite.x);
    AppendText(resultText, sizeof(resultText), "splitWhiteCIE.y    = %.6f\r\n", splitWhite.y);
    AppendText(resultText, sizeof(resultText), "splitWhiteCIE.Y    = %.6f\r\n\r\n", splitWhite.Y);

    AppendText(resultText, sizeof(resultText), "---------------- RGB Mixed Point splitPointCIE ----------------\r\n");
    AppendText(resultText, sizeof(resultText), "splitPointCIE.x    = %.6f\r\n", splitRgb.x);
    AppendText(resultText, sizeof(resultText), "splitPointCIE.y    = %.6f\r\n", splitRgb.y);
    AppendText(resultText, sizeof(resultText), "splitPointCIE.Y    = %.6f\r\n", splitRgb.Y);
    AppendText(resultText, sizeof(resultText), "rayT               = %.6f\r\n", rayT);
    AppendText(resultText, sizeof(resultText), "lambda             = %.6f\r\n\r\n", lambda);

    AppendText(resultText, sizeof(resultText), "---------------- RGB Weight and PWM Estimation ----------------\r\n");
    AppendText(resultText, sizeof(resultText), "RGB weight valid   = %u\r\n", rgbWeight.valid);
    AppendText(resultText, sizeof(resultText), "R weight           = %.6f\r\n", rgbWeight.r);
    AppendText(resultText, sizeof(resultText), "G weight           = %.6f\r\n", rgbWeight.g);
    AppendText(resultText, sizeof(resultText), "B weight           = %.6f\r\n", rgbWeight.b);
    AppendText(resultText, sizeof(resultText), "PWM R/G/B/W        = %d / %d / %d / %d\r\n", pwmR, pwmG, pwmB, pwmW);

    AppendText(resultText, sizeof(resultText), "\r\nNote: This GUI only calculates K-ratio method. It does not calculate Ra. Use MATLAB s07 for Ra.\r\n");

    SetWindowTextA(g_hwndResult, resultText);
}

